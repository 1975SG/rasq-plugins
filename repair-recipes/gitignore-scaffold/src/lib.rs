#[allow(warnings)]
mod bindings;

use bindings::exports::iderm::plugin::repair_recipe::Guest;
use bindings::iderm::plugin::host;
use bindings::iderm::plugin::types::{FileChange, ProjectInfo};

struct Component;

/// small, genuinely useful default -- not exhaustive, just the entries
/// almost every project wants regardless of language (editor swap
/// files, OS metadata, a generic `target`/`build`/`dist` catch-all).
/// language-specific entries are deliberately not attempted here: this
/// recipe has no way to know what languages a project actually uses
/// beyond what `ProjectInfo::languages` already reports, and guessing
/// wrong would be worse than a short, safe default.
const GITIGNORE_CONTENT: &str = "\
# Generated by example-repair-recipe
.DS_Store
*.swp
target/
build/
dist/
";

impl Guest for Component {
    fn recipe_id() -> String {
        "example-gitignore-scaffold".to_string()
    }

    /// mirrors `example-doctor-rule`'s own `.gitignore` check exactly --
    /// same read, same interpretation of "not found" -- so the doctor
    /// finding that flags the gap and the recipe that fixes it agree on
    /// what "present" means.
    fn applies_to(project: ProjectInfo) -> bool {
        let gitignore_path = format!("{}/.gitignore", project.root_path.trim_end_matches('/'));
        host::read_file(&gitignore_path).is_err()
    }

    /// proposes creating `.gitignore` -- never edits an existing one
    /// (Core's own `resolve_new_file_within_root` refuses that anyway,
    /// v1 scope, `docs/modules/Repair.md`). `diff` here is the literal
    /// new-file content per that same v1 convention, not a real unified
    /// diff.
    fn propose(_project: ProjectInfo) -> Result<Vec<FileChange>, String> {
        Ok(vec![FileChange {
            path: ".gitignore".to_string(),
            diff: GITIGNORE_CONTENT.to_string(),
            description: "Create a starter .gitignore".to_string(),
        }])
    }
}

bindings::export!(Component with_types_in bindings);
